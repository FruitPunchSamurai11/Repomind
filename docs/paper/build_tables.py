"""Build docs/paper/tables/repos.tex (Table I of the paper) from results/round2/*.csv.

One row per repository: the original 8 first, then the 12 sampled, in the
order of repos_round2.txt. Every number is read from the CSVs; nothing is
typed by hand. "--" marks a value the experiment did not produce (e.g. a
repository excluded from retrieval for having fewer than 20 issue-PR links).

Usage:  python docs/paper/build_tables.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results" / "round2"
OUT = Path(__file__).resolve().parent / "tables" / "repos.tex"

# The original 8 were hand-picked before the sampler existed, so their language is recorded here
# (GitHub's primary language); the sampled 12 take theirs from sample_chosen.csv.
ORIGINAL_LANG = {"pallets/flask": "Python", "psf/requests": "Python", "tiangolo/fastapi": "Python",
                 "BurntSushi/ripgrep": "Rust", "psf/black": "Python", "expressjs/express": "JavaScript",
                 "spf13/cobra": "Go", "sindresorhus/ora": "JavaScript"}
LANG_ABBR = {"Python": "Py", "JavaScript": "JS", "TypeScript": "TS", "Go": "Go", "Rust": "Rust", "Java": "Java"}


def by_repo(name: str) -> dict:
    with (RESULTS / name).open(newline="", encoding="utf-8") as f:
        return {r["repo"]: r for r in csv.DictReader(f)}


def repos_in_order() -> list[tuple[str, bool]]:
    out = []
    for line in (ROOT / "repos_round2.txt").read_text(encoding="utf-8").splitlines():
        name, _, comment = line.partition("#")
        if name.strip():
            out.append((name.strip(), "original" in comment))
    return out


def num(v, fmt):
    return "--" if v in (None, "") else fmt(float(v))


pct = lambda v: num(v, lambda x: f"{100 * x:.1f}")
pct0 = lambda v: num(v, lambda x: f"{100 * x:.0f}")
dec2 = lambda v: num(v, lambda x: f"{x:.2f}")
thousands = lambda v: num(v, lambda x: f"{int(x):,}".replace(",", "{,}"))
tex = lambda s: s.replace("_", r"\_")


def build() -> str:
    ds, lk, at = by_repo("dataset.csv"), by_repo("linkage.csv"), by_repo("attribution.csv")
    cc, rk, rt = by_repo("concentration.csv"), by_repo("risk.csv"), by_repo("retrieval.csv")
    lang = {r: d["language"] for r, d in by_repo("sample_chosen.csv").items()} | ORIGINAL_LANG
    lines = [
        r"\begin{tabular}{llrrrrrrrcrrrr}",
        r"\toprule",
        r"Repository & Lang. & Commits & \makecell{Ranked\\files} & \makecell{Human$\to$\\login \%} & "
        r"\makecell{GitHub\\attr. \%} & \makecell{PR$\to$\\files \%} & \makecell{Median\\$N_{\mathrm{eff}}$} & "
        r"\makecell{Top$\geq$80\%\\files \%} & \makecell{H/M/L\\$W$=365} & \makecell{Agree\\@180d \%} & "
        r"\makecell{Agree\\@730d \%} & \makecell{BM25\\R@10 \%} & \makecell{Fusion\\R@10 \%} \\",
        r"\midrule",
    ]
    order = repos_in_order()
    for i, (repo, original) in enumerate(order):
        if i and not original and order[i - 1][1]:
            lines.append(r"\midrule")
        r = rt.get(repo, {})
        ok_retrieval = r.get("status") == "ok"
        risk = rk[repo]
        cells = [tex(repo.split("/")[1]), LANG_ABBR[lang[repo]], thousands(ds[repo]["commits"]),
                 thousands(cc[repo]["ranked_files"]), pct(lk[repo]["human_commits_linked_share"]),
                 pct(at[repo]["github_attributed_share"]), pct(lk[repo]["pr_file_link_rate"]),
                 dec2(cc[repo]["median_neff_files"]), pct(cc[repo]["files_top_share_ge80"]),
                 f"{risk['high']}/{risk['medium']}/{risk['low']}",
                 pct0(risk["agreement_with_180d"]), pct0(risk["agreement_with_730d"]),
                 pct(r.get("bm25_r10")) if ok_retrieval else "--",
                 pct(r.get("minmax_r10")) if ok_retrieval else "--"]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("% Generated by docs/paper/build_tables.py from results/round2/*.csv -- do not edit by hand.\n"
                   + build(), encoding="utf-8")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
